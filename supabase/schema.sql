-- IterationsCLI — Supabase schema
-- Run once in the Supabase SQL editor (Dashboard → SQL → New query). Safe to re-run.
--
-- After running it:
--   1. Dashboard → Project Settings → API → "Exposed schemas": add `iterations`.
--   2. Set the environment variables listed in README.md ("Supabase").
--
-- The app signs users in itself (bcrypt password + a JWT cookie signed with
-- JWT_SECRET) and talks to these tables only from its server routes
-- (app/api/auth/*, app/api/kamako/*). It does not use Supabase Auth.

create schema if not exists iterations;

-- Accounts (app/api/auth/*)
create table if not exists iterations.users (
  user_id    bigint generated by default as identity primary key,
  username   text not null unique,
  password   text not null,              -- bcrypt hash, never the plain password
  created_at timestamptz not null default now()
);

-- Account board used by /dashboard (app/api/kamako/route.ts)
create table if not exists iterations.boards (
  board_id   bigint generated by default as identity primary key,
  user_id    bigint not null references iterations.users (user_id) on delete cascade,
  name       text not null default 'starterBoard',
  created_at timestamptz not null default now()
);
create index if not exists boards_user_id_idx on iterations.boards (user_id);

-- Column and ticket ids may be supplied by the client (app/api/kamako/columns, /tickets).
create table if not exists iterations.columns (
  column_id     bigint generated by default as identity primary key,
  board_id      bigint not null references iterations.boards (board_id) on delete cascade,
  column_header text,
  created_at    timestamptz not null default now()
);
create index if not exists columns_board_id_idx on iterations.columns (board_id);

create table if not exists iterations.tickets (
  ticket_id          bigint generated by default as identity primary key,
  column_id          bigint not null references iterations.columns (column_id) on delete cascade,
  ticket_header      text,
  ticket_description text,
  created_at         timestamptz not null default now()
);
create index if not exists tickets_column_id_idx on iterations.tickets (column_id);

-- Workspace sync (app/api/kamako/workspace/route.ts): one JSON document per
-- account holding the alpha workspace — tasks, columns, labels, whiteboard
-- items, drawings, saved pen colors, checkpoints.
create table if not exists iterations.workspaces (
  user_id    bigint primary key references iterations.users (user_id) on delete cascade,
  data       jsonb not null,
  updated_at timestamptz not null default now()
);

-- Access -----------------------------------------------------------------------
-- Row level security is on with no policies, so the publishable/anon key can
-- read nothing by itself. The server routes need a key that may:
--
--   Recommended: set SUPABASE_SERVICE_ROLE_KEY on the server (never NEXT_PUBLIC_).
--   The service role bypasses RLS; nothing else is required.
alter table iterations.users      enable row level security;
alter table iterations.boards     enable row level security;
alter table iterations.columns    enable row level security;
alter table iterations.tickets    enable row level security;
alter table iterations.workspaces enable row level security;

grant usage on schema iterations to service_role;
grant all on all tables in schema iterations to service_role;
grant all on all sequences in schema iterations to service_role;

